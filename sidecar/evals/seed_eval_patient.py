#!/usr/bin/env python3
"""Generate the idempotent SQL seed for the live-eval dedicated patients.

Prints SQL to stdout; pipe it into the OpenEMR DB, e.g.:

    python evals/seed_eval_patient.py | \\
      docker exec -i <openemr-container> mysql -h mysql -uroot -proot openemr

Seeds the two patients the live sweep needs deterministic data for (both use
ids well above the Synthea cohort's max, so they never collide):

  * pid 999 — a STALE-ACTIVE Warfarin row (activity flag set, but end_date in the
    past), the data-quality trap uc6 asserts the agent hedges on. No Synthea
    patient reliably carries one.

  * pid 998 — a WRONG-CHART patient. Its chart identity (Evan Testchart /
    1950-01-01 / Male) deliberately differs from its SINGLE uploaded intake form
    (the committed synthetic_intake_form.png = Jordan A. Rivera / 1968-03-12 /
    Female — a 3-way name/DOB/sex mismatch). Because it has exactly one intake
    form and it is an unambiguous mismatch (unlike the demo patient, which
    carries both matching and mismatching fixtures), get_intake_form resolves
    deterministically and uc_wrong_chart reliably flags the mismatch.

Idempotent: deletes then re-inserts, so it is safe to apply before every sweep.
"""
import base64
import os

_HERE = os.path.dirname(os.path.abspath(__file__))
_FIXTURE = os.path.join(_HERE, "..", "fixtures", "documents", "synthetic_intake_form.png")


def main() -> None:
    with open(_FIXTURE, "rb") as fh:
        b64 = base64.b64encode(fh.read()).decode("ascii")

    print("-- Auto-generated by evals/seed_eval_patient.py — do not edit by hand.")
    print("DELETE FROM lists WHERE pid IN (998, 999);")
    print("DELETE FROM documents WHERE foreign_id = 998;")
    print("DELETE FROM patient_data WHERE pid IN (998, 999);")

    # pid 999 — stale-active anticoagulant (uc6): active flag set, end_date past,
    # so the medications tool reports status_conflict=true and the agent hedges.
    print(
        "INSERT INTO patient_data (pid, pubpid, fname, lname, DOB, sex, date) "
        "VALUES (999, 'EVAL999', 'Eval', 'Patient', '1950-01-01', 'Male', NOW());"
    )
    print(
        "INSERT INTO lists (pid, type, title, activity, begdate, enddate, date, diagnosis) "
        "VALUES (999, 'medication', 'Warfarin 5 mg daily', 1, "
        "'2023-01-01 00:00:00', '2024-06-01 00:00:00', NOW(), '');"
    )

    # pid 998 — wrong-chart: chart identity differs from the intake form's, and
    # the intake form is the ONLY document on file (get_documents is foreign_id
    # scoped; getDocument returns the document_data blob the extractor reads).
    print(
        "INSERT INTO patient_data (pid, pubpid, fname, lname, DOB, sex, date) "
        "VALUES (998, 'EVAL998', 'Evan', 'Testchart', '1950-01-01', 'Male', NOW());"
    )
    print(
        "INSERT INTO documents "
        "(foreign_id, mimetype, name, documentationOf, docdate, date, revision, deleted, document_data) "
        f"VALUES (998, 'image/png', 'synthetic_intake_form.png', 'intake_form', "
        f"NOW(), NOW(), NOW(), 0, '{b64}');"
    )


if __name__ == "__main__":
    main()
